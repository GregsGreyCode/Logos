import { createRequire } from 'module';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright-core');
const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) process.exitCode = 1; };
const browser = await chromium.launch({ executablePath: process.env.CHROME });
const ctx = await browser.newContext({ viewport: { width: 412, height: 915 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 });
const page = await ctx.newPage(); const errs = []; page.on('pageerror', (e) => errs.push(e.message));
await page.addInitScript(() => { try { localStorage.setItem('fake.groups', '10'); } catch (e) {} });
await page.goto('http://127.0.0.1:8779/#/chat'); await page.waitForTimeout(2500);
const rows = () => page.locator('.void-groups a.void-group');
ok(await rows().count() === 8 && await page.locator('.void-more').count() === 1, `12 chats: the first 8, then "${await page.locator('.void-more').innerText().catch(() => '')}"`);
ok(await page.locator('.void-group.with-pic .agent-mark').count() >= 1 && await page.locator('.void-avatar.group').count() >= 1, 'each chat has its picture (agent mark or group icon)');
await page.locator('.void-more').tap(); await page.waitForTimeout(300);
ok(await rows().count() === 12, 'Show more shows all 12');
await page.locator('.void-filters .chip', { hasText: 'Agents' }).tap(); await page.waitForTimeout(300);
ok(await rows().count() === 1 && (await rows().first().innerText()).includes("Greg's agent"), 'Agents: only agent chats');
await page.locator('.void-filters .chip', { hasText: 'Groups' }).tap(); await page.waitForTimeout(300);
ok(await rows().count() === 8, 'Groups: groups (first 8)');
await page.locator('.void-filters .chip', { hasText: 'All' }).tap(); await page.waitForTimeout(300);
await page.fill('.void-search', 'trip'); await page.waitForTimeout(400);
ok(await rows().count() === 4 && await page.evaluate(() => document.activeElement?.classList.contains('void-search')), `search finds the 4 trips and keeps typing in the box (${await rows().count()})`);
await page.screenshot({ path: process.argv[2] + '/chatlist-phone.png', fullPage: true });
await page.evaluate(() => { location.hash = '#/home'; }); await page.waitForTimeout(800);
await page.evaluate(() => { location.hash = '#/chat'; }); await page.waitForTimeout(1500);
ok(await rows().count() === 8, 'a fresh visit starts from All again');
ok(errs.length === 0, `no page errors ${errs.join('|')}`);
await browser.close();
