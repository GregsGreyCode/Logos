import { createRequire } from 'module';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright-core');
const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) process.exitCode = 1; };
const browser = await chromium.launch({ executablePath: process.env.CHROME });
const ctx = await browser.newContext({ viewport: { width: 412, height: 915 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 });
const page = await ctx.newPage(); const errs = []; page.on('pageerror', (e) => errs.push((e.stack || e.message).split('\n').slice(0, 2).join(' < ')));
const posts = []; page.on('request', (r) => { if (r.method() === 'POST' && r.url().includes('/notifications')) posts.push(`${new URL(r.url()).pathname} ${r.postData()}`); });
await page.goto('http://127.0.0.1:8779/#/noticeboard'); await page.waitForTimeout(2500);
const fresh = () => page.locator('.notifications .feed-item.fresh').count();
const n0 = await fresh();
ok(n0 >= 3, `starts with new items (${n0})`);
ok(!posts.some((p) => p.includes('/seen')), 'opening the tab no longer marks everything seen');
const brain = page.locator('.notifications .feed-item', { hasText: 'pages changed' }).first();
await brain.tap(); await page.waitForTimeout(400);
ok(await brain.getAttribute('aria-expanded') === 'true' && await brain.locator('.feed-go').isVisible(), 'a tap opens it, with an Open button');
ok(!(await brain.getAttribute('class')).includes('fresh') && await fresh() === n0 - 1, 'and it is no longer new');
ok(posts.some((p) => p.includes('/read') && p.includes('"ids":["brain:')), `read sent (${posts.at(-1)})`);
const msg = page.locator('.notifications .feed-item.kind-chat').first();
await msg.tap(); await page.waitForTimeout(500);
ok((await page.evaluate(() => window.__mx.receipts || [])).length === 1, 'a message tapped is marked read in Matrix too');
ok(await msg.locator('.feed-text').evaluate((el) => getComputedStyle(el).whiteSpace) === 'normal', 'its whole text shows');
await page.screenshot({ path: process.argv[2] + '/nr-open.png' });
await msg.tap(); await page.waitForTimeout(200);
ok(await msg.getAttribute('aria-expanded') === 'false', 'a second tap closes it');
await page.locator('.feed-allread').tap(); await page.waitForTimeout(500);
ok(posts.some((p) => p.includes('"all":true')), 'Mark all read');
ok(errs.length === 0, `no page errors ${errs.join(' | ')}`);
await browser.close();
