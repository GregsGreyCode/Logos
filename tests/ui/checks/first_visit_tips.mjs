import { createRequire } from 'module';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright-core');
const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) process.exitCode = 1; };
const browser = await chromium.launch({ executablePath: process.env.CHROME });
const ctx = await browser.newContext({ viewport: { width: 412, height: 915 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 });
const page = await ctx.newPage(); const errs = []; page.on('pageerror', (e) => errs.push(e.message));
let seen = [];
const puts = [];
await page.route('**/api/v2/me', async (route) => { const r = await route.fetch(); const d = await r.json(); d.prefs.tips_seen = seen; await route.fulfill({ json: d }); });
await page.route('**/api/v2/me/prefs', async (route) => { const b = JSON.parse(route.request().postData()); puts.push(b); if (b.tips_seen) seen = b.tips_seen; await route.fulfill({ json: { ok: true } }); });
await page.goto('http://127.0.0.1:8779/#/home'); await page.waitForTimeout(2500);
const card = page.locator('.tip-card');
ok(await card.count() === 1 && (await card.innerText()).includes('Your day at a glance'), 'first visit to Home shows its tips');
await page.screenshot({ path: process.argv[2] + '/tip-home1.png' });
await card.getByRole('button', { name: 'Next' }).tap(); await page.waitForTimeout(500);
ok(await page.locator('.home-edit-link.tip-target').count() === 1, 'step 2 outlines Edit Home');
{ const r = await page.locator('.home-edit-link').boundingBox(), c = await card.boundingBox(); ok(r.y + r.height < c.y || r.y > c.y + c.height, 'and Edit Home is not under the card'); }
await page.screenshot({ path: process.argv[2] + '/tip-home2.png' });
await card.getByRole('button', { name: 'Next' }).tap(); await page.waitForTimeout(300);
await card.getByRole('button', { name: 'Got it' }).tap(); await page.waitForTimeout(300);
ok(await card.count() === 0 && await page.locator('.tip-target').count() === 0, 'Got it closes it');
ok(JSON.stringify(puts.at(-1)) === '{"tips_seen":["home"]}', `remembered with the login (${JSON.stringify(puts.at(-1))})`);
await page.evaluate(() => { location.hash = '#/noticeboard'; }); await page.waitForTimeout(1500);
ok((await card.innerText()).includes('What happened'), 'Notifications has its own tips');
await page.evaluate(() => { location.hash = '#/home'; }); await page.waitForTimeout(1500);
ok(await card.count() === 0, 'leaving mid-tip closes it, and Home does not show again');
await page.evaluate(() => { location.hash = '#/chat'; }); await page.waitForTimeout(1500);
ok((await card.innerText()).includes('Your agents'), 'Agents has its tips');
await page.screenshot({ path: process.argv[2] + '/tip-agents.png' });
await card.getByRole('button', { name: 'Skip tips' }).tap(); await page.waitForTimeout(300);
ok(puts.at(-1).tips_seen.length === 5, 'Skip tips turns them all off');
await page.reload(); await page.waitForTimeout(2000);
await page.evaluate(() => { location.hash = '#/noticeboard'; }); await page.waitForTimeout(1500);
ok(await card.count() === 0, 'after Skip, nowhere shows tips');
await page.evaluate(() => { location.hash = '#/settings/appearance'; }); await page.waitForTimeout(1500);
await page.getByRole('button', { name: 'Show the tips again' }).tap(); await page.waitForTimeout(300);
ok(JSON.stringify(puts.at(-1)) === '{"tips_seen":[]}', 'Settings › Show the tips again');
await page.evaluate(() => { location.hash = '#/home'; }); await page.waitForTimeout(1500);
ok(await card.count() === 1, 'and Home shows them again');
ok(errs.length === 0, `no page errors ${errs.join('|')}`);
await browser.close();
