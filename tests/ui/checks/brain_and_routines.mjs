import { createRequire } from 'module';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright-core');
const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) process.exitCode = 1; };
const browser = await chromium.launch({ executablePath: process.env.CHROME });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
await page.goto('http://127.0.0.1:8779/#/brain/greg'); await page.waitForTimeout(2200);
const foot = await page.locator('.doc-foot').innerText();
ok(!/Changed \./.test(foot), `brain footer reads well: "${foot}"`);
const heads = await page.$$eval('.tree-head', (els) => els.map((e) => { const l = e.querySelector('.label').getBoundingClientRect(), b = e.querySelector('.tree-add')?.getBoundingClientRect(); return b ? Math.abs((l.top + l.height / 2) - (b.top + b.height / 2)) : 0; }));
ok(heads.every((d) => d <= 3), `each + level with its heading (${heads.map(Math.round)})`);
await page.screenshot({ path: process.argv[2] + '/desk/b2-brain.png' });
await page.goto('http://127.0.0.1:8779/#/agents/greg'); await page.waitForTimeout(2000);
const cards = await page.locator('.agent-cards').boundingBox(), list = await page.locator('.routines').boundingBox();
ok(Math.abs(cards.width - list.width) <= 2, `routines: picker as wide as the list (${Math.round(cards.width)} / ${Math.round(list.width)})`);
await page.screenshot({ path: process.argv[2] + '/desk/b2-routines.png' });
await browser.close();
